import { chromium } from 'playwright-core'
import { BASE_URL, SHOTS } from './helpers.mjs'
const b = await chromium.launch()
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m)
const errs = []
let p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
await p.goto(BASE_URL); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(800)
const panel = '.lead-detail'
ok((await p.locator('.lead-row:has-text("Ananya") .lead-flag.shared').innerText()) === 'Also with 6 brokers', 'lead row shows "Also with 6 brokers"')
ok(await p.locator('.lead-row:has-text("Deepak") .lead-flag').count() === 1 && (await p.locator('.lead-row:has-text("Deepak") .lead-flag').innerText()) === 'Overdue', 'one flag per row: Overdue wins over shared (Deepak)')
await p.click('.lead-row:has-text("Ananya")')
ok(await p.locator(`${panel} .shared-lead`).isVisible(), 'shared-lead warning in panel')
ok(await p.locator(`${panel} .lead-detail-tabs button`).count() === 3, 'three tabs: Overview / Timeline / Notes')
// Edit brief: invalid then valid
await p.click(`${panel} .brief-edit`); await p.waitForTimeout(300)
await p.fill('.edit-lead input[placeholder="e.g. 2.4"]', '3'); await p.fill('.edit-lead input[placeholder="e.g. 2.8"]', '2')
ok(await p.locator('.edit-lead .form-error').isVisible() && await p.locator('.edit-lead .add-lead-submit').isDisabled(), 'max < min shows error and disables Save')
await p.fill('.edit-lead input[placeholder="e.g. 2.4"]', '2.5'); await p.fill('.edit-lead input[placeholder="e.g. 2.8"]', '3')
await p.fill('.edit-lead input[placeholder="e.g. Indiranagar, Domlur"]', 'Indiranagar, Domlur')
await p.click('.edit-lead .add-lead-submit'); await p.waitForTimeout(300)
ok((await p.locator(`${panel} .lead-detail-heading h2`).innerText()) === '₹2.5–3 Cr', 'heading shows new budget ₹2.5–3 Cr')
ok((await p.locator(`${panel} .buyer-brief div:has-text("Localities") strong`).innerText()) === 'Indiranagar, Domlur', 'localities saved')
// Tags
await p.click(`${panel} .tag-chip.add`); await p.click(`${panel} .lead-tags-picker .tag-chip:has-text("Loan needed")`)
ok(await p.locator(`${panel} .tag-chip.applied:has-text("Loan needed")`).count() === 1, 'tag "Loan needed" applied')
await p.fill(`${panel} .lead-tags-picker input`, 'Corner unit'); await p.press(`${panel} .lead-tags-picker input`, 'Enter')
ok(await p.locator(`${panel} .tag-chip.applied`).count() === 2, 'custom tag added')
// Notes
await p.click(`${panel} .lead-detail-tabs button:has-text("Notes")`)
await p.fill(`${panel} .lead-notes textarea`, 'Prefers morning visits; father joins.'); await p.click(`${panel} .lead-notes .btn`)
ok(await p.locator(`${panel} .lead-notes article`).count() === 1 && (await p.locator(`${panel} .lead-detail-tabs button:has-text("Notes")`).innerText()) === 'Notes · 1', 'note added, tab shows "Notes · 1"')
// Timeline
await p.click(`${panel} .lead-detail-tabs button:has-text("Timeline")`)
const items = await p.locator(`${panel} .lead-timeline li p`).allInnerTexts()
ok(items[0].startsWith('Note:') && items.some(t => t.startsWith('Buyer brief updated')) && items.some(t => t === 'Tagged Loan needed'), 'timeline: newest demo events first (note, tags, brief update)')
ok(items.at(-1) === 'First enquiry via 99acres' && items.some(t => t.startsWith('Assigned to Priya Nair by routing')) && items.some(t => t.startsWith('Visit planned')), 'timeline: seed events (enquiry last, routing, visit)')
await p.screenshot({ path: `${SHOTS}/m5-timeline.png` })
await p.click(`${panel} .lead-detail-tabs button:has-text("Overview")`); await p.screenshot({ path: `${SHOTS}/m5-overview.png`, fullPage: false })
// Duplicate + merge (owner, visible lead)
await p.click('.sidebar-nav button:has-text("Today")'); await p.click('.sidebar-add')
await p.fill('.add-lead input[placeholder="e.g. Priya Menon"]', 'Ananya R'); await p.fill('.add-lead .phone-input input', '9886124018')
ok(await p.locator('.duplicate-alert:has-text("This number is already Ananya Rao")').isVisible(), 'duplicate alert names Ananya Rao')
ok(await p.locator('.duplicate-alert .btn:has-text("Open lead")').count() === 1, 'Open lead offered when visible')
await p.screenshot({ path: `${SHOTS}/m5-duplicate.png` })
await p.click('.duplicate-alert .btn:has-text("Merge enquiry")'); await p.waitForTimeout(200)
ok((await p.locator('.add-lead h2').innerText()) === 'Enquiry merged', 'merge confirmation shown')
await p.click('.add-lead .btn-primary'); await p.waitForTimeout(200)
await p.click('.inbox-more'); ok(await p.locator('.lead-row').count() === 46, 'no duplicate lead created (still 46)')
await p.click('.lead-row:has-text("Ananya")'); await p.click(`${panel} .lead-detail-tabs button:has-text("Notes")`)
ok((await p.locator(`${panel} .lead-notes article p`).first().innerText()).startsWith('New enquiry merged'), 'merged enquiry recorded as a note')
// Duplicate from a Sales viewer for another team's lead
await p.click('.sidebar-user .account-menu-trigger'); await p.click('.account-menu-popover button:has-text("Priya Nair")'); await p.waitForTimeout(300)
await p.click('.sidebar-nav button:has-text("Today")'); await p.click('.sidebar-add'); await p.fill('.add-lead .phone-input input', '9845561207')
ok((await p.locator('.duplicate-alert small').innerText()).includes('(another team)') && await p.locator('.duplicate-alert .btn:has-text("Open lead")').count() === 0, 'other team\'s duplicate: flagged, no Open button')
await p.close()
// Phone: details sheet tabs + edit
p = await b.newPage({ viewport: { width: 390, height: 844 } }); p.on('pageerror', e => errs.push(e.message))
await p.goto(BASE_URL); await p.waitForTimeout(800)
await p.click('.lead-row:has-text("Deepak")'); await p.click('.chat-details-button'); await p.waitForTimeout(500)
await p.screenshot({ path: `${SHOTS}/m5-mob-sheet.png` })
await p.click('.dialog-sheet .brief-edit'); await p.waitForTimeout(500)
ok(await p.locator('.edit-lead').isVisible() && await p.locator('.dialog-sheet').count() === 0, 'phone: Edit closes the sheet and opens the form')
await p.screenshot({ path: `${SHOTS}/m5-mob-edit.png` })
console.log('errors:', errs.length ? errs : 'none'); await b.close()
