import { chromium } from 'playwright-core'
import { BASE_URL, SHOTS } from './helpers.mjs'
const b = await chromium.launch()
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m)
const errs = []
let p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
await p.goto(BASE_URL); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(800)
const nav = (l) => p.click(`.sidebar-nav button:has-text("${l}")`)
const menu = async (item) => { await p.click('.sidebar-user .account-menu-trigger'); await p.click(`.account-menu-popover button:has-text("${item}")`); await p.waitForTimeout(300) }
await nav('Lead sources')
ok(await p.locator('.source-row').count() === 8, '8 sources listed')
const stat = (i) => p.locator('.stat-strip > div strong').nth(i).innerText()
ok(await stat(0) === '168' && await stat(1) === '₹43,170' && await stat(2) === '₹257', `totals: 168 leads, ₹43,170 spend, ₹257 blended (got ${await stat(0)}, ${await stat(1)}, ${await stat(2)})`)
await p.fill('.source-row:has-text("99acres") .source-input input', '500'); await p.waitForTimeout(100)
ok(await stat(1) === '₹45,070', 'editing 99acres cost to ₹500 updates spend to ₹45,070')
await p.screenshot({ path: `${SHOTS}/m3-sources.png` })
// Simulate from account menu (owner, pre-sales first)
await menu('Simulate incoming lead')
ok(await p.locator('.incoming-lead:has-text("New lead · 99acres")').isVisible(), 'banner: New lead · 99acres')
ok((await p.locator('.incoming-lead').innerText()).includes('Meera Iyer') && (await p.locator('.incoming-lead').innerText()).includes('Assigned to Lakshmi Narayan'), 'Meera Iyer routed to Lakshmi (pre-sales, fewest leads)')
await p.screenshot({ path: `${SHOTS}/m3-banner.png` })
await p.click('.incoming-lead .btn:has-text("Reply now")'); await p.waitForTimeout(300)
ok(await p.locator('.chat-person strong').innerText() === 'Meera Iyer' && (await p.locator('.messages .message').first().innerText()).includes('Can I visit this weekend') && await p.locator('.messages .message-auto').count() >= 1, 'Reply now opens chat: buyer’s enquiry, then the automatic reply')
ok(await p.locator('.quick-replies .chip').first().innerText() === 'Send a welcome message', 'fresh lead offers welcome message')
await p.click('.lead-detail .lead-detail-tabs button:has-text("Timeline")')
ok((await p.locator('.lead-detail .lead-timeline li p').allInnerTexts()).some(t => t.startsWith('New enquiry via 99acres · routed to Lakshmi Narayan')), 'timeline records the arrival and routing')
await nav('Today'); ok(await p.locator('.lead-row').count() === 13, 'inbox now has 13 leads')
// By-source routing, pre-sales off
await nav('Settings'); await p.click('.setting-row'); await p.click('.routing-options button:has-text("By source")')
await nav('Lead sources'); await p.selectOption('.source-row:has-text("Housing") .source-team select', 'whitefield')
await p.click('.source-row:has-text("Housing") .btn:has-text("Simulate")'); await p.waitForTimeout(300)
const txt = await p.locator('.incoming-lead').innerText()
ok(txt.toLowerCase().includes('new lead · housing') && /Assigned to (Ayesha Khan|Karthik Srinivas)/.test(txt), `by-source: Housing lead goes to a Whitefield salesperson (${txt.match(/Assigned to [^\n·]+/)?.[0]})`)
await p.click('.incoming-lead .btn:has-text("Dismiss")')
// Disconnect
await p.click('.source-row:has-text("MagicBricks") .btn:has-text("Disconnect")')
ok(await p.locator('.source-row:has-text("MagicBricks") .btn:has-text("Simulate")').isDisabled() && (await p.locator('.source-row:has-text("MagicBricks") .source-status').innerText()).includes('Not connected'), 'disconnected source cannot simulate')
// Source filter
await nav('Today'); await p.selectOption('.source-filter', 'Walk-in')
ok(await p.locator('.lead-row').count() === 1 && (await p.locator('.lead-row strong').first().innerText()) === 'Pooja Venkatesh', 'source filter Walk-in shows only Pooja')
await p.selectOption('.source-filter', 'All')
// Sales viewer: no Lead sources, simulated lead not visible -> no Reply button
await menu('Priya Nair')
ok(await p.locator('.sidebar-nav button:has-text("Lead sources")').count() === 0, 'sales: no Lead sources screen')
await menu('Simulate incoming lead')
const t2 = await p.locator('.incoming-lead').innerText()
ok(await p.locator('.incoming-lead .btn:has-text("Reply now")').count() === (t2.includes('Priya Nair') ? 1 : 0), `sales: Reply now only if the lead is theirs (${t2.match(/Assigned to [^\n·]+/)?.[0]})`)
await menu('Neha Kapoor')
ok(await p.locator('.sidebar-nav button:has-text("Lead sources")').count() === 1, 'manager: Lead sources visible')
await nav('Lead sources'); ok(await p.locator('.source-input').count() === 0 && await p.locator('.source-team select').first().isDisabled(), 'manager: read-only (no cost inputs, team locked)')
await p.close()
// Phone banner + sources layout
p = await b.newPage({ viewport: { width: 390, height: 844 } }); p.on('pageerror', e => errs.push(e.message))
await p.goto(BASE_URL); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(800)
await p.click('.mobile-top-bar .account-menu-trigger'); await p.click('.account-menu-popover button:has-text("Simulate incoming lead")'); await p.waitForTimeout(500)
const bb = await p.locator('.incoming-lead').boundingBox(); ok(bb && bb.y >= 60 && bb.x >= 8 && bb.x + bb.width <= 382, 'phone banner sits under the top bar, inside the screen')
await p.screenshot({ path: `${SHOTS}/m3-mob-banner.png` })
await p.click('.mobile-tab-bar button:has-text("More")'); await p.waitForTimeout(300); await p.click('.more-sheet button:has-text("Lead sources")'); await p.waitForTimeout(400)
ok(await p.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), 'phone sources: no sideways scroll')
await p.screenshot({ path: `${SHOTS}/m3-mob-sources.png`, fullPage: true })
console.log('errors:', errs.length ? errs : 'none'); await b.close()
