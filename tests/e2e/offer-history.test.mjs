import { chromium } from 'playwright-core'
import { BASE_URL, SHOTS } from './helpers.mjs'
const b = await chromium.launch()
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m)
const errs = []
let p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
await p.goto(BASE_URL); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(800)
const nav = (l) => p.click(`.sidebar-nav button:has-text("${l}")`)
await nav('Pipeline')
const neg = p.locator('.pipeline-stage[aria-label="Negotiation"]')
const rm = neg.locator('.deal-card:has-text("Rohan & Meera")')
ok((await rm.locator('.deal-budget').innerText()).includes('₹3.2 Cr'), 'card shows latest buyer offer ₹3.2 Cr with its date')
ok((await rm.locator('.deal-stale-flag').innerText()) === 'No new offer in 9 days', 'stale flag on Rohan & Meera (9 days)')
ok(await neg.locator('.deal-card:has-text("Lavanya") .deal-stale-flag').count() === 0, 'no stale flag on Lavanya (2 days)')
await p.screenshot({ path: `${SHOTS}/m14-pipeline.png` })
// Lead panel history
await rm.locator('.deal-person').click(); await p.waitForTimeout(300)
const hist = await p.locator('.lead-detail .deal-offers li').allInnerTexts()
ok(hist.length === 3 && hist[0].startsWith('Buyer offered') && hist[0].includes('₹3.2 Cr') && hist[1].startsWith('Owner countered'), `history newest first: ${hist.map(h => h.split('\n').join(' ')).join(' | ')}`)
ok((await p.locator('.lead-detail .deal-stale').innerText()).includes('No new offer in 9 days'), 'stale note in the deal panel')
// Log an owner counter dated yesterday + agreement date + token
await p.click('.lead-detail .deal-panel .brief-edit')
ok(await p.locator('.deal-dialog .offer-list li').count() === 3, 'dialog lists 3 offers')
await p.click('.offer-new .segmented button:has-text("Owner counter")')
await p.fill('.offer-new input', '3.3')
await p.selectOption('.offer-new select', '-1')
await p.click('.offer-new .btn:has-text("Add")')
ok(await p.locator('.deal-dialog .offer-list li').count() === 4 && (await p.locator('.deal-dialog .offer-list li').first().innerText()).includes('₹3.3 Cr'), 'counter added at the top')
await p.fill('.offer-new input', '0')
ok((await p.locator('.deal-dialog .form-error').innerText()).includes('offer amount'), 'zero offer refused')
await p.fill('.offer-new input', '3.25')  // buyer offer typed but not "Add"ed: saved anyway
await p.click('.offer-new .segmented button:has-text("Buyer offer")')
await p.selectOption('.offer-new select', '0')
await p.selectOption('.deal-dialog label:has-text("Agreement by") select', '10')
await p.fill('.deal-dialog label:has-text("Token amount") input', '5')
await p.selectOption('.deal-dialog label:has-text("Token paid on") select', '0')
await p.screenshot({ path: `${SHOTS}/m14-dialog.png` })
await p.click('.deal-dialog .add-lead-submit'); await p.waitForTimeout(300)
const hist2 = await p.locator('.lead-detail .deal-offers li').allInnerTexts()
ok(hist2.length === 5 && hist2[0].includes('₹3.25 Cr') && hist2[0].includes('Today') && hist2[1].includes('₹3.3 Cr') && hist2[1].includes('Yesterday'), 'pending offer saved; dates shown')
ok(await p.locator('.lead-detail .deal-stale').count() === 0, 'stale note gone after a new offer')
const panel = await p.locator('.lead-detail .deal-panel').innerText()
ok(panel.includes('₹5 L · paid today') && panel.includes('Agreement by'), 'token date and agreement date shown')
await p.screenshot({ path: `${SHOTS}/m14-panel.png` })
await p.click('.lead-detail button:has-text("Timeline")')
const tl = await p.locator('.lead-timeline').innerText()
ok(tl.includes('Owner countered ₹3.3 Cr (dated Yesterday)') && tl.includes('Buyer offered ₹3.25 Cr'), 'each offer logged on the timeline with its date')
await p.click('.lead-detail button:has-text("Overview")')
// Remove an offer
await p.click('.lead-detail .deal-panel .brief-edit'); await p.click('.offer-list li >> nth=0 >> button'); await p.click('.deal-dialog .add-lead-submit'); await p.waitForTimeout(200)
ok(await p.locator('.lead-detail .deal-offers li').count() === 4, 'an offer can be removed')
// Win prefills agreed with latest buyer offer
await p.click('.lead-detail .deal-panel .btn-primary:has-text("Mark won")')
ok((await p.locator('.deal-dialog label:has-text("Agreed price") input').inputValue()) === '3.2', 'win dialog prefills latest buyer offer')
await p.keyboard.press('Escape')
await nav('Pipeline')
ok(await rm.locator('.deal-stale-flag').count() === 0 && (await rm.locator('.deal-budget').innerText()).includes('Yesterday') === false, 'pipeline card updated')
// Phone
await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(300)
await p.click('.stage-tabs button:has-text("Negotiation")'); await p.click('.pipeline-stage.phone-visible .deal-card:has-text("Lavanya") .deal-person'); await p.waitForTimeout(300)
await p.click('.chat-details-button'); await p.waitForTimeout(300)
await p.click('.dialog .deal-panel .brief-edit'); await p.waitForTimeout(300)
ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'phone: no sideways scroll')
const add = await p.locator('.offer-new .segmented button').first().boundingBox()
ok(add && add.height >= 44, 'phone: offer controls 44px')
await p.screenshot({ path: `${SHOTS}/m14-phone.png` })
ok(errs.length === 0, 'no console errors ' + errs.join(' | '))
await b.close()
