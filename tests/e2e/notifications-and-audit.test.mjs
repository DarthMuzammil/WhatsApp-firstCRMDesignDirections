import { chromium } from 'playwright-core'
import { BASE_URL, SHOTS } from './helpers.mjs'
import fs from 'fs'
const b = await chromium.launch()
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m)
const errs = []
let p = await b.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true })
p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
await p.goto(BASE_URL); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(800)
const nav = (l) => p.click(`.sidebar-nav button:has-text("${l}")`)
const viewAs = async (n) => { await p.click('.sidebar-user .account-menu-trigger'); await p.click(`.account-menu-popover button:has-text("${n}")`); await p.waitForTimeout(300) }
const bell = '.sidebar-head .notification-bell'
const badge = async () => (await p.locator(`${bell} .count-badge`).count()) ? await p.locator(`${bell} .count-badge`).innerText() : '0'
const tab = (t) => p.click(`.attendance-tabs button:has-text("${t}")`)
// Owner seed
ok(await badge() === '3', 'owner: 3 unread (incl. the overdue developer invoice)')
await p.click(bell)
ok(await p.locator('.notification-list li').count() === 4, 'owner: 4 notifications')
ok((await p.locator('.notification-attention').innerText()).includes('waiting over 15 min'), 'needs-attention row for overdue leads')
await p.screenshot({ path: `${SHOTS}/m12-panel.png` })
await p.click('.notification-list button:has-text("check-in")'); await p.waitForTimeout(300)
ok((await p.locator('h1').innerText()).length > 0 && await p.locator('.sidebar-nav button.active:has-text("Visits")').count() === 1, 'refused check-in opens Visits')
ok(await badge() === '2', 'badge drops to 2')
await p.click(bell); await p.click('.notifications-head-buttons .btn:has-text("Mark all read")')
ok(await p.locator('.notification-list button.unread').count() === 0, 'mark all read'); await p.keyboard.press('Escape')
ok(await badge() === '0', 'badge hidden')
// Reassign Ananya (Priya) → Aditya; Priya hears about it
await nav('Today'); await p.click('.lead-row:has-text("Ananya")'); await p.click('.lead-owner-card .btn:has-text("Reassign")')
await p.click('.assign-list button:has-text("Aditya Rao")'); await p.click('.assign-confirm'); await p.waitForTimeout(300)
// Settings change twice → one coalesced audit entry
await nav('Settings'); await p.click('button[role="radio"]:has-text("300 m")'); await p.click('button[role="radio"]:has-text("500 m")'); await p.click('button[role="radio"]:has-text("200 m")')
await nav('Audit log')
ok((await p.locator('h1').innerText()) === 'Audit log', 'owner: Audit log screen')
const texts = await p.locator('.audit-list li p').allInnerTexts()
ok(texts[0] === 'Check-in radius set to 200 m' && texts.filter(t => t.startsWith('Check-in radius')).length === 2, `repeated setting edits coalesce (1 new + 1 seed): ${texts.slice(0, 2).join(' | ')}`)
ok(texts.some(t => t.startsWith('Reassigned Ananya Rao from Priya N. to Aditya R.')), 'reassignment audited')
await p.click('.audit-view .chip:has-text("Reassignments")')
ok(await p.locator('.audit-list li').count() === 3, 'filter Reassignments: 2 seed + 1 new')
await p.click('.audit-view .chip:has-text("All")')
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('.audit-exports .btn:has-text("Export leads")')])
const csv = fs.readFileSync(await dl.path(), 'utf8').split('\n')
ok(dl.suggestedFilename() === 'daira-leads.csv' && csv.length === 47 && csv[0].startsWith('Name,Phone,Source,Owner'), `leads CSV: header + 46 rows (${csv.length})`)
ok(csv.some(l => l.startsWith('Ananya Rao,+91') && l.includes('Aditya Rao')), 'CSV has full numbers and current owner')
ok((await p.locator('.audit-list li p').first().innerText()) === 'Exported leads as CSV (46 rows)', 'export audited')
await p.screenshot({ path: `${SHOTS}/m12-audit.png`, fullPage: true })
// Priya: moved-away notification; applies for leave → Neha notified → approves → Priya notified
await viewAs('Priya Nair')
ok(await p.locator('.sidebar-nav button:has-text("Audit log")').count() === 0, 'sales: no Audit log')
ok(await badge() === '3', 'Priya: 2 seed (incl. a registration expiring) + reassignment = 3 unread')
await p.click(bell)
ok((await p.locator('.notification-list li').first().innerText()).includes('Ananya Rao moved to Aditya R.'), 'Priya told Ananya moved')
await p.keyboard.press('Escape')
await nav('Attendance'); await tab('Leave')
await p.selectOption('.leave-form select >> nth=1', '4'); await p.selectOption('.leave-form select >> nth=2', '5'); await p.fill('.leave-form input', 'Sister’s wedding'); await p.click('.leave-form .btn'); await p.waitForTimeout(200)
await viewAs('Neha Kapoor')
ok(await p.locator('.sidebar-nav button:has-text("Audit log")').count() === 0, 'manager: no Audit log')
await p.click(bell)
ok((await p.locator('.notification-list li').first().innerText()).includes('Priya N. asked for 2 days of Casual leave'), 'manager notified of leave request')
await p.click('.notification-list li >> nth=0 >> button'); await p.waitForTimeout(300)
ok(await p.locator('.sidebar-nav button.active:has-text("Attendance")').count() === 1, 'opens Attendance')
await tab('Requests'); await p.click('.leave-requests .request-row:has-text("Priya Nair") .btn:has-text("Approve")'); await p.click('.assign-list button:has-text("Divya Iyer")'); await p.click('.assign-confirm'); await p.waitForTimeout(300)
await viewAs('Priya Nair'); await p.click(bell)
ok((await p.locator('.notification-list li').first().innerText()).includes('leave was approved. Divya I. will cover'), 'Priya told leave approved')
await p.keyboard.press('Escape')
// Phone
await viewAs('Arjun Khanna')
await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(300)
ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'phone: top bar fits')
const box = await p.locator('.mobile-top-bar .notification-bell').boundingBox()
ok(box && box.width >= 44 && box.height >= 44, 'phone: bell is 44px')
await p.click('.mobile-top-bar .notification-bell'); await p.waitForTimeout(300)
await p.screenshot({ path: `${SHOTS}/m12-phone.png` })
await p.keyboard.press('Escape')
await p.click('.mobile-tab-bar button:has-text("More")'); await p.click('.dialog button:has-text("Audit log")'); await p.waitForTimeout(300)
ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'phone: audit log fits')
await p.screenshot({ path: `${SHOTS}/m12-phone-audit.png`, fullPage: true })
ok(errs.length === 0, 'no console errors ' + errs.join(' | '))
await b.close()
