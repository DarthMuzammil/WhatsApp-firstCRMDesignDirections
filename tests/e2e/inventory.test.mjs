import { chromium } from 'playwright-core'
import { BASE_URL, SHOTS } from './helpers.mjs'
const b = await chromium.launch()
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m)
const errs = []
let p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
await p.goto(BASE_URL); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(800)
const nav = (l) => p.click(`.sidebar-nav button:has-text("${l}")`)
const viewAs = async (n) => { await p.click('.sidebar-user .account-menu-trigger'); await p.click(`.account-menu-popover button:has-text("${n}")`); await p.waitForTimeout(300) }
const openLead = async (name) => { await nav('Today'); await p.click(`.lead-row:has-text("${name}")`); await p.waitForTimeout(300) }
await nav('Properties')
ok(await p.locator('.listing').count() === 8, '8 listings')
ok((await p.locator('.properties-view .page-head p').innerText()) === '6 available · 1 on hold · 1 sold', 'status counts')
ok((await p.locator('.listing:has-text("Windermere") .listing-people').innerText()).includes('+91 99001 72244'), 'owner sees full owner number')
await p.click('.properties-filters .segmented button:has-text("Sold")')
ok(await p.locator('.listing').count() === 1 && await p.locator('.listing .btn-success').isDisabled(), 'Sold filter: 1, Share disabled')
await p.click('.properties-filters .segmented button:has-text("All")')
await p.screenshot({ path: `${SHOTS}/m11-properties.png`, fullPage: true })
// Add
await p.click('.properties-view .page-head .btn-primary')
await p.click('.property-dialog .add-lead-submit')
ok((await p.locator('.property-dialog .form-error').innerText()).includes('name'), 'validation: name required')
await p.fill('.property-dialog label:has-text("Property name") input', 'Banyan Court')
await p.selectOption('.property-dialog label:has-text("Locality") select', 'Koramangala')
await p.fill('.property-dialog label:has-text("Asking price") input', '2.2')
await p.fill('.property-dialog label:has-text("Carpet area") input', '1450')
await p.fill('.property-dialog label:has-text("Owner’s name") input', 'Ravi Kumar')
await p.fill('.property-dialog .phone-input input', '98765')
await p.click('.property-dialog .add-lead-submit')
ok((await p.locator('.property-dialog .form-error').innerText()).includes('10-digit'), 'validation: owner mobile')
await p.fill('.property-dialog .phone-input input', '9876543210')
await p.screenshot({ path: `${SHOTS}/m11-add.png` })
await p.click('.property-dialog .add-lead-submit'); await p.waitForTimeout(200)
const banyan = p.locator('.listing:has-text("Banyan Court")')
ok(await banyan.count() === 1 && await banyan.locator('.property-photo-empty').count() === 1 && (await banyan.innerText()).includes('Added today'), 'added with placeholder photo')
ok(await p.locator('.locality-chips button:has-text("Koramangala")').count() === 1, 'new locality chip')
// Edit Brookside on hold → available
await p.click('.listing:has-text("Brookside") button[aria-label^="Edit"]')
await p.click('.property-dialog .segmented button:has-text("Available")'); await p.click('.property-dialog .add-lead-submit'); await p.waitForTimeout(200)
ok((await p.locator('.listing:has-text("Brookside") .listing-status').innerText()).toLowerCase() === 'available', 'edit availability')
// Share from listing
await p.click('.listing:has-text("Courtyard") .btn-success')
const first = await p.locator('.share-dialog .assign-list > button').first().innerText()
ok(first.includes('Ananya Rao') || first.includes('Ishita') || first.includes('Gaurav'), `best-fitting buyer first: ${first.split('\n')[0]}`)
ok(first.includes('Indiranagar · 3 BHK'), 'reasons shown in lead picker')
await p.click('.share-dialog .assign-list > button:has-text("Ananya Rao")')
ok(await p.locator('.share-list button[aria-pressed="true"]').count() === 1, 'listing pre-ticked')
ok((await p.locator('.share-bubble').innerText()).includes('The Courtyard House'), 'WhatsApp preview')
await p.screenshot({ path: `${SHOTS}/m11-share.png` })
await p.click('.share-footer .btn-success'); await p.waitForTimeout(200)
await openLead('Ananya Rao')
ok(await p.locator('.message-shared .property-card:has-text("Courtyard")').count() === 1, 'shared card in chat')
await p.waitForTimeout(4300)
ok(await p.locator('.message-shared .message-seen').count() === 1, '"Seen" after a few seconds')
ok((await p.locator('.lead-detail .match-reasons').first().innerText()).includes('Seen'), 'panel shows Seen on the match')
// Matches with reasons for Farhan
await openLead('Farhan')
