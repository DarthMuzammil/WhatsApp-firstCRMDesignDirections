import { chromium } from 'playwright-core'
import { BASE_URL, SHOTS } from './helpers.mjs'
const b = await chromium.launch()
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m)
const errs = []
let p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', e => errs.push(e.message))
await p.goto(BASE_URL); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(800)
ok(await p.locator('.today-view .page-head .btn-primary').count() === 0, 'Today header has no duplicate Add lead')
await p.click('.sidebar-nav button:has-text("Pipeline")'); await p.click('.sidebar-add')
ok(await p.locator('.add-lead').isVisible(), 'Add lead opens from Pipeline via the sidebar'); await p.keyboard.press('Escape')
await p.click('.sidebar-nav button:has-text("Today")'); await p.click('.due-item >> nth=0'); await p.waitForTimeout(300)
ok((await p.locator('.chat-layout header').first().innerText()).includes('Ananya Rao'), 'Due today item opens the lead’s chat')
await p.click('.chat-layout header button[aria-label="Back"], .chat-layout header .icon-button >> nth=0'); await p.waitForTimeout(200)
ok(await p.locator('.sidebar-nav button.active:has-text("Today")').count() === 1, 'Back returns to Today')
await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(300)
await p.click('.lead-row >> nth=0'); await p.waitForTimeout(300)
await p.click('.chat-mobile-actions button:has-text("Share homes")'); await p.click('.share-footer .btn-success'); await p.waitForTimeout(300)
const t = await p.locator('.toast').boundingBox(); const c = await p.locator('.composer, .chat-composer, form').last().boundingBox()
ok(t && t.y < 150, `phone toast at the top (y=${t?.y})`)
await p.screenshot({ path: `${SHOTS}/quick-phone-toast.png` })
await p.setViewportSize({ width: 1440, height: 900 }); await p.waitForTimeout(300)
await p.screenshot({ path: `${SHOTS}/quick-sidebar.png` })
ok(errs.length === 0, 'no errors ' + errs.join('|'))
await b.close()
