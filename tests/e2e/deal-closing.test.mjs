import { chromium } from 'playwright-core'
import { BASE_URL, SHOTS } from './helpers.mjs'
const b = await chromium.launch()
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m)
const errs = []
let p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
await p.goto(BASE_URL); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(800)
const nav = (l) => p.click(`.sidebar-nav button:has-text("${l}")`)
const vivekCommission = async () => { await nav('Performance'); return parseFloat((await p.locator('.reports-grid .bar-list li:has-text("Vivek Sharma") .bar-track b').innerText()).replace(/[^\d.]/g, '')) }
const before = await vivekCommission()
await nav('Pipeline')
ok(await p.locator('.pipeline-stage').count() === 5, 'five columns incl. Closed')
const neg = p.locator('.pipeline-stage[aria-label="Negotiation"]')
const rm = neg.locator('.deal-card:has-text("Rohan & Meera")')
ok((await rm.locator('.deal-budget').innerText()).includes('3.2'), 'seeded offer ₹3.2 Cr shown on card')
ok(await p.locator('.deal-advance:visible, .deal-won:visible, .deal-lost:visible, .deal-back:visible').count() === 0, 'desktop: no move buttons on cards (drag and drop only)')
const closedCol = () => p.locator('.pipeline-stage[aria-label="Closed"]')
// While a card is dragged, Closed shows a Won zone and, below it, a Lost zone.
const dropWon = (card) => card.dragTo(closedCol(), { targetPosition: { x: 80, y: 90 } })
const dropLost = (card) => card.dragTo(closedCol(), { targetPosition: { x: 80, y: 196 } })
await dropWon(rm)
ok((await p.locator('.deal-dialog input').nth(2).inputValue()) === '3.2', 'win dialog pre-fills agreed with offer')
await p.click('.deal-dialog .btn:has-text("Add person")')
await p.locator('.deal-dialog .split-row').nth(0).locator('input').fill('80')
ok(await p.locator('.deal-dialog .form-error').isVisible() && await p.locator('.deal-dialog .add-lead-submit').isDisabled(), 'split must total 100%')
await p.locator('.deal-dialog .split-row').nth(1).locator('input').fill('20')
await p.click('.deal-dialog .add-lead-submit'); await p.waitForTimeout(200)
const closed = p.locator('.pipeline-stage[aria-label="Closed"]')
ok((await closed.locator('.deal-card:has-text("Rohan & Meera") .deal-outcome').innerText()).includes('Won at ₹3.2 Cr'), 'won → Closed column')
const after = await vivekCommission()
ok(Math.abs(after - before - 5.1) < 0.15, `Vivek commission +₹5.1 L (3.2 Cr × 2% × 80%): ${before} → ${after}`)
await nav('Pipeline')
await dropLost(neg.locator('.deal-card:has-text("Lavanya")'))
await p.selectOption('.confirm-dialog .lost-reason select', 'Stopped responding')
await p.click('.confirm-dialog .btn-danger'); await p.waitForTimeout(200)
ok((await closed.locator('.deal-card:has-text("Lavanya")').innerText()).includes('Stopped responding'), 'lost with reason in Closed')
// Columns are long now: drop near the top of the target column (its header), which is always on screen.
await closed.locator('.deal-card:has-text("Lavanya")').dragTo(neg, { targetPosition: { x: 80, y: 24 } })
ok(await neg.locator('.deal-card:has-text("Lavanya")').count() === 1 && (await p.locator('.toast').innerText()).includes('reopened'), 'drag a closed card back to a stage reopens it there')
const ananya = p.locator('.deal-card:has-text("Ananya Rao")')
const fromStage = await ananya.evaluate(e => e.closest('.pipeline-stage').getAttribute('aria-label'))
await ananya.dragTo(p.locator('.pipeline-stage[aria-label="Qualified"]'), { targetPosition: { x: 80, y: 24 } })
const toStage = await ananya.evaluate(e => e.closest('.pipeline-stage').getAttribute('aria-label'))
ok(fromStage !== toStage, `move back: ${fromStage} → ${toStage}`)
await ananya.dragTo(p.locator('.pipeline-stage[aria-label="Negotiation"]'), { targetPosition: { x: 80, y: 24 } })
ok(await neg.locator('.deal-card:has-text("Ananya Rao")').count() === 1, 'drag and drop to Negotiation')
await p.screenshot({ path: `${SHOTS}/m10-pipeline.png`, fullPage: true })
// Lead panel deal card
await neg.locator('.deal-card:has-text("Lavanya") .deal-person').click(); await p.waitForTimeout(300)
const panel = p.locator('.lead-detail .deal-panel')
ok((await panel.innerText()).includes('₹4.2 Cr'), 'deal panel shows asking price')
await panel.locator('.deal-docs button:has-text("Token receipt")').click()
ok(await panel.locator('.deal-docs button:has-text("Token receipt")').getAttribute('aria-pressed') === 'true', 'doc checklist toggles')
await p.click('.lead-detail button:has-text("Timeline")')
ok((await p.locator('.lead-timeline').innerText()).includes('Token receipt received'), 'doc logged on timeline')
await p.click('.lead-detail button:has-text("Overview")')
await p.screenshot({ path: `${SHOTS}/m10-panel.png` })
await nav('Pipeline')
ok((await p.locator('.stat-strip div:has-text("Open deals") strong').innerText()) === '45', 'Pipeline: 45 open deals after 1 won (46 seeded)')
// Phone
await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(300)
await p.click('.mobile-tab-bar button:has-text("Pipeline")')
await p.click('.stage-tabs button:has-text("Closed")')
ok(await p.locator('.pipeline-stage.phone-visible .deal-card').count() === 1, 'phone: Closed tab shows the won deal')
await p.click('.stage-tabs button:has-text("Negotiation")')
ok(await p.locator('.pipeline-stage.phone-visible .deal-won').first().isVisible(), 'phone: Won / Lost buttons still on cards (no dragging on touch)')
await p.screenshot({ path: `${SHOTS}/m10-phone.png`, fullPage: true })
ok(errs.length === 0, 'no console errors ' + errs.join(' | '))
await b.close()
